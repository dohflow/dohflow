#!/usr/bin/env node
/**
 * Generate docs/product/shipped-features.md — the ORACLE the website copy is
 * checked against.
 *
 * The site must not claim a feature the app does not have. Marketing copy drifts
 * from reality by accident, not malice: a bead gets descoped, a feature is cut,
 * the page keeps its sentence. This file is the source of truth for "what can we
 * honestly say ships today", generated from closed feature beads rather than
 * from anyone's memory, and n76x.16 greps site copy against it.
 *
 * Usage:  node scripts/generate-shipped-features.mjs [--check]
 *   --check  exit 1 if the committed file is stale (for CI)
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const OUT = 'docs/product/shipped-features.md'

// Invoke the real bd binary. A shell alias on the maintainer's machine points
// `bd` at an older incompatible CLI, so resolve the absolute path rather than
// relying on PATH order. See AGENTS.md §9.0.
function bd(args) {
  for (const bin of [`${process.env.HOME}/.local/bin/bd`, 'bd']) {
    try {
      return execFileSync(bin, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    } catch (e) {
      if (e.code === 'ENOENT') continue
      throw e
    }
  }
  throw new Error('bd not found')
}

// --limit 0 is REQUIRED: bd defaults to 50 and silently truncates. An oracle
// that omits shipped features is worse than none — CI would reject copy that is
// actually true, and the fix would look like "loosen the check".
const beads = JSON.parse(bd(['list', '--type=feature', '--status=closed', '--json', '--limit', '0']))
if (beads.length >= 50 && beads.length % 50 === 0) {
  console.warn(`warning: got exactly ${beads.length} features — verify --limit 0 is honoured`)
}

// Strip the "FEATURE: " prefix the older beads carry; it is noise in a list
// that is entirely features.
const clean = (t) => t.replace(/^FEATURE:\s*/i, '').trim()

const rows = beads
  .map((b) => ({ id: b.id, title: clean(b.title), priority: b.priority }))
  .sort((a, b) => a.id.localeCompare(b.id))

let changelog = ''
if (existsSync('CHANGELOG.md')) {
  const raw = readFileSync('CHANGELOG.md', 'utf8')
  // Everything above the second version heading = the current/unreleased set.
  const heads = [...raw.matchAll(/^##\s+.+$/gm)]
  changelog = heads.length > 1 ? raw.slice(heads[0].index, heads[1].index).trim() : raw.trim()
}

const body = `# Shipped features — the copy oracle

<!-- GENERATED by scripts/generate-shipped-features.mjs — do not edit by hand. -->

**This file exists so the website cannot claim something the app does not do.**

Every line below is a **closed** feature bead: work that merged. Site copy is
checked against this list by CI. If a page wants to claim a capability that is
not here, either the claim is wrong or the bead is not closed — fix whichever is
actually untrue, never the check.

A closed bead means the work merged. It does **not** by itself mean the feature
is polished, discoverable, or worth putting on a marketing page. Use this list
as a **ceiling on claims**, not a to-do list of things to advertise.

Generated ${new Date().toISOString().slice(0, 10)} · ${rows.length} shipped features

| Bead | Feature |
|---|---|
${rows.map((r) => `| \`${r.id.replace('personal-cfo-', '')}\` | ${r.title} |`).join('\n')}

## Current changelog section

${changelog || '_No CHANGELOG.md found._'}
`

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  // The generated date line changes daily and would make --check fail every day
  // for no reason. Compare everything else.
  const strip = (s) => s.replace(/^Generated \d{4}-\d{2}-\d{2} · /m, 'Generated · ')
  if (strip(current) !== strip(body)) {
    console.error(`${OUT} is stale — run: node scripts/generate-shipped-features.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is current (${rows.length} features)`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote ${OUT} — ${rows.length} shipped features`)
}
